import { Principal, Permission } from '../types/iam';

export interface RemediationPackage {
  principalName: string;
  originalPolicyJson: string;
  leastPrivilegePolicyJson: string;
  diffHtml: { line: string; type: 'added' | 'removed' | 'unchanged' }[];
  terraformCode: string;
  awsCliCommand: string;
  removedPermissionsCount: number;
  retainedPermissionsCount: number;
}

/**
 * Synthesizes a strict Least-Privilege IAM Policy for a given Principal
 */
export function generateLeastPrivilegePolicy(principal: Principal): RemediationPackage {
  const granted = principal.grantedPermissions || [];
  const activePermissions = granted.filter((p) => p.isUsed);
  const unusedPermissions = granted.filter((p) => !p.isUsed);

  // Group active permissions by service
  const activeActions = activePermissions.map((p) => p.action);
  const unusedActions = unusedPermissions.map((p) => p.action);

  // Original policy structure
  const originalDoc = {
    Version: '2012-10-17',
    Statement: [
      {
        Sid: 'OriginalOverPrivilegedPolicy',
        Effect: 'Allow',
        Action: granted.map((p) => p.action),
        Resource: '*',
      },
    ],
  };

  // Least-privilege right-sized structure
  const leastPrivDoc = {
    Version: '2012-10-17',
    Statement: [
      {
        Sid: 'RightSizedLeastPrivilegePolicy',
        Effect: 'Allow',
        Action: activeActions.length > 0 ? activeActions : ['none:NoActiveUsageDetected'],
        Resource: '*',
      },
    ],
  };

  const originalPolicyJson = JSON.stringify(originalDoc, null, 2);
  const leastPrivilegePolicyJson = JSON.stringify(leastPrivDoc, null, 2);

  // Generate Git-style line diff
  const diffHtml: { line: string; type: 'added' | 'removed' | 'unchanged' }[] = [
    { line: '{', type: 'unchanged' },
    { line: '  "Version": "2012-10-17",', type: 'unchanged' },
    { line: '  "Statement": [', type: 'unchanged' },
    { line: '    {', type: 'unchanged' },
    { line: '      "Effect": "Allow",', type: 'unchanged' },
    { line: '      "Action": [', type: 'unchanged' },
  ];

  for (const act of activeActions) {
    diffHtml.push({ line: `        "${act}",  // [RETAINED - ACTIVE USE]`, type: 'added' });
  }

  for (const act of unusedActions) {
    diffHtml.push({ line: `        "${act}",  // [REMOVED - NEVER EXERCISED]`, type: 'removed' });
  }

  diffHtml.push(
    { line: '      ],', type: 'unchanged' },
    { line: '      "Resource": "*"', type: 'unchanged' },
    { line: '    }', type: 'unchanged' },
    { line: '  ]', type: 'unchanged' },
    { line: '}', type: 'unchanged' }
  );

  // Generate Terraform HCL snippet
  const cleanId = principal.name.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  const terraformCode = `# Auto-generated by Cloud Identity Risk Analyzer
# Department of CSE, Bharati Vidyapeeth's College of Engineering

resource "aws_iam_policy" "${cleanId}_least_privilege" {
  name        = "${cleanId}-least-privilege-policy"
  description = "Strict least-privilege policy right-sized from CloudTrail audit analysis"

  policy = jsonencode({
    Version = "2012-10-17"
    Statement = [
      {
        Effect   = "Allow"
        Action   = ${JSON.stringify(activeActions.length > 0 ? activeActions : ['none:NoActiveUsageDetected'], null, 8)}
        Resource = "*"
      }
    ]
  })
}

resource "aws_iam_${principal.type === 'Role' ? 'role' : 'user'}_policy_attachment" "${cleanId}_attach" {
  ${principal.type === 'Role' ? 'role' : 'user'}       = "${principal.name}"
  policy_arn = aws_iam_policy.${cleanId}_least_privilege.arn
}
`;

  // AWS CLI Command
  const awsCliCommand = `# Step 1: Detach over-privileged policies
aws iam detach-${principal.type === 'Role' ? 'role' : 'user'}-policy \\
  --${principal.type === 'Role' ? 'role' : 'user'}-name "${principal.name}" \\
  --policy-arn "arn:aws:iam::aws:policy/AdministratorAccess"

# Step 2: Apply right-sized least-privilege policy
aws iam put-${principal.type === 'Role' ? 'role' : 'user'}-policy \\
  --${principal.type === 'Role' ? 'role' : 'user'}-name "${principal.name}" \\
  --policy-name "${cleanId}-least-privilege" \\
  --policy-document file://least_privilege_policy.json
`;

  return {
    principalName: principal.name,
    originalPolicyJson,
    leastPrivilegePolicyJson,
    diffHtml,
    terraformCode,
    awsCliCommand,
    removedPermissionsCount: unusedActions.length,
    retainedPermissionsCount: activeActions.length,
  };
}
